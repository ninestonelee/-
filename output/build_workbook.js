// ---------- helpers ----------
const run = (text, opts = {}) => new TextRun({ text, font: FONT, size: opts.size || 20, bold: opts.bold, color: opts.color, italics: opts.italics });

function p(text, opts = {}) {
  const runs = Array.isArray(text) ? text : [run(text, opts)];
  return new Paragraph({
    children: runs,
    spacing: { before: opts.before ?? 60, after: opts.after ?? 60, line: opts.line ?? 300 },
    alignment: opts.align,
    indent: opts.indent,
  });
}
function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    children: [run(text, { size: 34, bold: true, color: "1F3864" })],
    spacing: { before: 200, after: 160 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 12, color: "1F3864", space: 4 } },
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    children: [run(text, { size: 26, bold: true, color: "1F3864" })],
    spacing: { before: 240, after: 100 },
  });
}
function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    children: [run(text, { size: 22, bold: true })],
    spacing: { before: 160, after: 60 },
  });
}
function bullets(items, ref = "bul") {
  return items.map((t) => new Paragraph({
    children: Array.isArray(t) ? t : [run(t)],
    numbering: { reference: ref, level: 0 },
    spacing: { before: 40, after: 40, line: 300 },
  }));
}
function numbered(items) {
  return items.map((t) => new Paragraph({
    children: Array.isArray(t) ? t : [run(t)],
    numbering: { reference: "num" + numCounter, level: 0 },
    spacing: { before: 40, after: 40, line: 300 },
  }));
}
let numCounter = 0;
const numRefs = [];
function newNumbered(items) { numCounter++; numRefs.push("num" + numCounter); return numbered(items); }

function pageBreak() { return new Paragraph({ children: [new PageBreak()] }); }

function cell(content, opts = {}) {
  const children = (Array.isArray(content) ? content : [content]).map((c) =>
    typeof c === "string" ? p(c, { size: opts.size || 19, bold: opts.bold, before: 40, after: 40, line: 280 }) : c);
  return new TableCell({
    children,
    width: { size: opts.width || 1000, type: WidthType.DXA },
    shading: opts.fill ? { fill: opts.fill, type: ShadingType.CLEAR, color: "auto" } : undefined,
    verticalAlign: opts.valign || VerticalAlign.TOP,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    borders: opts.borders || borders,
    columnSpan: opts.span,
  });
}
function table(colWidths, rows, opts = {}) {
  return new Table({
    width: { size: colWidths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    columnWidths: colWidths,
    rows: rows.map((r, i) => new TableRow({
      children: r.map((c, j) => (c instanceof TableCell ? c : cell(c, {
        width: colWidths[j],
        fill: i === 0 && opts.header !== false ? GRAY : undefined,
        bold: i === 0 && opts.header !== false,
      }))),
      tableHeader: i === 0 && opts.header !== false,
      cantSplit: true,
    })),
  });
}
// A shaded callout box
function box(title, lines, fill = ACCENT) {
  const content = [];
  if (title) content.push(p(title, { bold: true, size: 20, before: 40, after: 40 }));
  lines.forEach((l) => content.push(typeof l === "string" ? p(l, { size: 19, before: 30, after: 30, line: 280 }) : l));
  return new Table({
    width: { size: W, type: WidthType.DXA },
    columnWidths: [W],
    rows: [new TableRow({ children: [new TableCell({
      children: content, width: { size: W, type: WidthType.DXA },
      shading: { fill, type: ShadingType.CLEAR, color: "auto" },
      margins: { top: 100, bottom: 100, left: 160, right: 160 }, borders,
    })] })],
  });
}
// Example essay box with sentence labels
function example(title, sentences, notes) {
  const content = [p(title, { bold: true, size: 20, before: 40, after: 60 })];
  sentences.forEach(([label, text]) => content.push(p([run(label + " ", { bold: true, size: 19, color: "C00000" }), run(text, { size: 19 })], { before: 30, after: 30, line: 300 })));
  if (notes) { content.push(p("", { before: 20, after: 0 })); notes.forEach((n) => content.push(p([run("▶ ", { size: 18, color: "1F3864" }), run(n, { size: 18, color: "1F3864" })], { before: 20, after: 20, line: 260 }))); }
  return new Table({
    width: { size: W, type: WidthType.DXA }, columnWidths: [W],
    rows: [new TableRow({ children: [new TableCell({ children: content, width: { size: W, type: WidthType.DXA },
      shading: { fill: BLUE, type: ShadingType.CLEAR, color: "auto" }, margins: { top: 100, bottom: 100, left: 160, right: 160 }, borders })] })],
  });
}
// Ruled writing lines
function lines(n, label) {
  const out = [];
  if (label) out.push(p(label, { bold: true, size: 19, before: 120, after: 40 }));
  for (let i = 0; i < n; i++) {
    out.push(new Paragraph({
      children: [run(" ")],
      spacing: { before: 0, after: 0, line: 480 },
      border: { bottom: { style: BorderStyle.DOTTED, size: 6, color: "7F7F7F", space: 1 } },
    }));
  }
  return out;
}
// Writing box with char count
function writeBox(label, chars, n) {
  return [
    p([run(label, { bold: true, size: 20 }), run(chars ? `   공백 제외 ${chars}` : "", { size: 18, color: "C00000" })], { before: 160, after: 40 }),
    ...lines(n),
  ];
}
// Question table: question + blank answer area
function qa(questions, answerLines = 2) {
  const rows = [["번호", "질문", "내 답 (손으로 쓰기)"]];
  questions.forEach((q, i) => {
    const blanks = [];
    for (let k = 0; k < answerLines; k++) blanks.push(new Paragraph({ children: [run(" ")], spacing: { before: 0, after: 0, line: 440 }, border: { bottom: { style: BorderStyle.DOTTED, size: 4, color: "A6A6A6" } } }));
    rows.push([String(i + 1), q, new TableCell({ children: blanks, width: { size: 4800, type: WidthType.DXA }, borders, margins: { top: 60, bottom: 60, left: 100, right: 100 } })]);
  });
  return table([700, 4138, 4800], rows);
}
function checklist(items) {
  const rows = [["확인", "점검 항목"]];
  items.forEach((t) => rows.push(["☐", t]));
  return table([800, W - 800], rows);
}
function blankTable(headers, nRows, widths, rowHeightLines = 2) {
  const rows = [headers];
  for (let i = 0; i < nRows; i++) rows.push(headers.map(() => {
    const blanks = []; for (let k = 0; k < rowHeightLines; k++) blanks.push(p(" ", { line: 400 }));
    return blanks;
  }));
  return table(widths, rows);
}
function prefilledTable(headers, dataRows, widths, blankCols, rowHeightLines = 2) {
  const rows = [headers];
  dataRows.forEach((r) => rows.push(headers.map((_, j) => {
    if (blankCols.includes(j)) { const blanks = []; for (let k = 0; k < rowHeightLines; k++) blanks.push(p(" ", { line: 400 })); return blanks; }
    return r[j] ?? "";
  })));
  return table(widths, rows);
}
